"""VideoMind FastAPI application."""

import asyncio
import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

from app.config import Settings
from app.database import close_db, get_db
from app.routes import chat, generation, video
from app.schemas.video import HealthResponse
from app.services.embedding_service import embedding_service
from app.utils.errors import AppError

# Create settings instance (pydantic-settings reads .env at instantiation)
settings = Settings()

logging.basicConfig(
    level=getattr(logging, settings.log_level.upper(), logging.INFO),
    format="%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
)
logger = logging.getLogger("videomind")

_background_tasks: set[asyncio.Task] = set()


def _probe_database() -> None:
    get_db().ping()


async def _warm_up() -> None:
    """Pay the model-load and Neon TLS costs before the first user asks."""
    try:
        await asyncio.to_thread(embedding_service.warm_up)
        logger.info("Embedding model warmed up")
    except Exception as exc:  # pragma: no cover - depends on the model cache
        logger.warning("Embedding warm-up skipped: %s", exc)

    if settings.neon_configured:
        try:
            # The default executor keeps its threads, so each probe keeps a
            # reusable connection ready on a different worker thread.
            await asyncio.gather(*(asyncio.to_thread(_probe_database) for _ in range(3)))
            logger.info("Database connections warmed up")
        except Exception as exc:
            logger.warning("Database warm-up skipped: %s", exc)


@asynccontextmanager
async def lifespan(app: FastAPI):
    logger.info("Starting VideoMind API")
    logger.info("Chat model: %s", settings.groq_model)
    logger.info("Embedding model: %s", settings.embedding_model)
    missing = settings.missing_services()
    if missing:
        logger.warning("Missing service configuration: %s", ", ".join(missing))
    if settings.warm_up_on_startup and not missing:
        task = asyncio.create_task(_warm_up())
        _background_tasks.add(task)
        task.add_done_callback(_background_tasks.discard)
    yield
    await close_db()
    logger.info("VideoMind API stopped")


app = FastAPI(
    title="VideoMind API",
    version="1.0.0",
    description=(
        "Retrieval-augmented chat over YouTube transcripts. "
        "Transcripts are chunked, embedded with Sentence Transformers and stored in "
        "Neon PostgreSQL (pgvector); answers are generated by Groq from retrieved context."
    ),
    lifespan=lifespan,
    docs_url="/docs",
    redoc_url="/redoc",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_origin_regex=settings.cors_allow_origin_regex,
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.exception_handler(AppError)
async def app_error_handler(request: Request, exc: AppError) -> JSONResponse:
    return JSONResponse(status_code=exc.status_code, content={"error": exc.to_dict()})


@app.exception_handler(RequestValidationError)
async def validation_error_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    first = exc.errors()[0] if exc.errors() else {}
    location = ".".join(str(part) for part in first.get("loc", []) if part != "body")
    message = first.get("msg", "The request is not valid.")
    readable = f"{location}: {message}" if location else message
    return JSONResponse(
        status_code=422,
        content={"error": {"code": "validation_error", "message": readable}},
    )


@app.exception_handler(StarletteHTTPException)
async def http_error_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
    message = exc.detail if isinstance(exc.detail, str) else "Request failed."
    return JSONResponse(
        status_code=exc.status_code,
        content={"error": {"code": f"http_{exc.status_code}", "message": message}},
    )


@app.exception_handler(Exception)
async def unhandled_error_handler(request: Request, exc: Exception) -> JSONResponse:
    logger.exception("Unhandled error on %s %s", request.method, request.url.path)
    return JSONResponse(
        status_code=500,
        content={
            "error": {
                "code": "internal_error",
                "message": "Something went wrong on the server. Please try again.",
            }
        },
    )


app.include_router(video.router)
app.include_router(chat.router)
app.include_router(generation.router)


@app.get("/", include_in_schema=False)
async def root():
    return {
        "name": "VideoMind API",
        "version": "1.0.0",
        "docs": "/docs",
        "health": "/api/health",
    }


@app.get("/api/health", response_model=HealthResponse, tags=["system"])
async def health():
    missing = settings.missing_services()
    return HealthResponse(
        status="ok" if not missing else "degraded",
        services={
            "database": "configured" if settings.neon_configured else "missing",
            "groq": "configured" if settings.groq_configured else "missing",
            "whisper_fallback": "enabled" if settings.enable_whisper_fallback else "disabled",
        },
        embedding_model=settings.embedding_model,
        chat_model=settings.groq_model,
    )
